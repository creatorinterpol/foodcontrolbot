def get_current_week_cycle(target_date: date = None) -> int:
    """
    Определяет номер недели в цикле (1 или 2).
    Базовая дата: неделя 19-25 октября 2026 года — Неделя 1 (цикл 1).
    """
    if target_date is None:
        target_date = date.today()

    base_monday = date(2026, 10, 19)
    current_monday = target_date - timedelta(days=target_date.weekday())
    weeks_passed = (current_monday - base_monday).days // 7
    cycle_week = (weeks_passed % 2) + 1
    return cycle_week


def get_target_menu_date(now_dt: datetime = None) -> date:
    """
    Определяет целевую дату для меню:
    - До 14:00 (пн-сб) -> меню на СЕГОДНЯ.
    - После 14:00 (пн-пт) -> меню на ЗАВТРА.
    - В субботу после 14:00 или в воскресенье -> меню на ПОНЕДЕЛЬНИК.
    """
    if now_dt is None:
        moscow_tz = pytz.timezone('Europe/Moscow')
        now_dt = datetime.now(moscow_tz)

    today = now_dt.date()
    weekday = today.weekday()  # 0=Пн .. 5=Сб, 6=Вс
    hour = now_dt.hour

    if weekday == 6:  # Воскресенье -> всегда понедельник
        return today + timedelta(days=1)

    if hour >= 14:
        if weekday == 5:  # Суббота после 14:00 -> понедельник
            return today + timedelta(days=2)
        else:  # Пн-Пт после 14:00 -> завтра
            return today + timedelta(days=1)
    else:
        return today


def get_today_menu() -> str:
    """Возвращает полное меню (каждая позиция с новой строчки со смайликом)"""
    target_date = get_target_menu_date()
    weekday = target_date.weekday()

    if weekday == 6:
        return "🏖 Сегодня воскресенье — столовая не работает.\n\nПриятных выходных!"

    cycle_week = get_current_week_cycle(target_date)
    menu_dict = MENU_WEEK_2 if cycle_week == 2 else MENU_WEEK_1
    return menu_dict.get(weekday, "Меню не найдено")


def get_today_menu_compact() -> str:
    """Для отображения меню используется красивый полный формат с эмодзи на каждой строчке"""
    return get_today_menu()


def get_menu_for_date(target_date: date) -> str:
    """Получить меню для конкретной даты"""
    weekday = target_date.weekday()
    if weekday == 6:
        return "🏖 Воскресенье — выходной день"
    cycle_week = get_current_week_cycle(target_date)
    menu_dict = MENU_WEEK_2 if cycle_week == 2 else MENU_WEEK_1
    return menu_dict.get(weekday, "Меню не найдено")


def get_menu_compact_for_date(target_date: date) -> str:
    return get_menu_for_date(target_date)